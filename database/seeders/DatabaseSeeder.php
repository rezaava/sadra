    private function seedServiceItem(
        Service $service,
        int $number,
        string $icon,
        string $title,
        string $text,
        array $tags
    ): void {
        $item = ServiceItem::create([
            'service_id' => $service->id,
            'number' => $number,
            'icon' => $icon,
            'title' => $title,
            'text' => $text,
        ]);

        foreach ($tags as $tag) {
            ServiceItemTag::create([
                'service_item_id' => $item->id,
                'name' => $tag,
            ]);
        }
    }
