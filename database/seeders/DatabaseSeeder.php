        string $title,
        string $image,
        string $description,
        string $about,
        array $features
    ): void {
        $product = new Products();

        $product->name = $name;
        $product->title = $title;
        $product->category_id = $categoryId;
        $product->image = $image;
        $product->description = $description;
        $product->about = $about;
        $product->is_active = true;

